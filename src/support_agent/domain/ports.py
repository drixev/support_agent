from typing import Protocol

from support_agent.domain.models import Ticket
from support_agent.domain.rag import Chunk, ScoredChunk


class TicketRepository(Protocol):
    async def get(self, ticket_id:str) -> Ticket | None: ...
    async def search(self, query: str, limit: int = 10) -> list[Ticket]: ...
    async def save(self, ticket: Ticket)-> None: ...
    

class Embedder(Protocol):
    def dim(self) -> int: ...
    async def embed_documents(self, texts: list[str]) -> list[list[float]]: ...
    async def embed_query(self, text: str) -> list[float]: ...
    

class VectorStore(Protocol):
    async def upsert(self, chunks: list[Chunk], vectors: list[list[float]]) -> None: ...
    async def search(self, vector: list[float], k: int) -> list[ScoredChunk]: ...
    

class KeywordIndex(Protocol):
    def search(self, query: str, k: int) -> list[ScoredChunk]: ...
